const { chromium } = require('playwright')
;(async () => {
  const browser = await chromium.launch()
  const page = await browser.newPage()
  console.log('📸 SoundGit UI/UX Değerlendirmesi - Görsel Beyin\n')
  // 1. Landing
  await page.goto('https://soundgit.online/', { waitUntil: 'networkidle' })
  await page.setViewportSize({ width: 1920, height: 1080 })
  await page.screenshot({ path: 'landing-desktop.png', fullPage: true })
  console.log('✅ Landing desktop screenshot: landing-desktop.png')
  await page.setViewportSize({ width: 375, height: 812 })
  await page.screenshot({ path: 'landing-mobile.png', fullPage: true })
  console.log('✅ Landing mobile screenshot: landing-mobile.png')
  // Landing UI/UX check
  const landingChecks = await page.evaluate(() => {
    const checks = []
    const title = document.querySelector('h1, [class*="SOUNDGIT"]')
    checks.push({ item: 'Başlık var mı', ok: !!title, note: title?.textContent?.slice(0,30) })
    const sineWave = document.querySelector('canvas')
    checks.push({ item: 'Sine wave animasyon (canvas)', ok: !!sineWave, note: sineWave ? 'var' : 'yok - v19 da kaldırılmış olabilir' })
    const openStudio = document.querySelector('a, button') 
    checks.push({ item: 'Open Studio butonu', ok: !!openStudio })
    const googleLogin = document.body.innerHTML.includes('Google') || document.body.innerHTML.includes('Giriş')
    checks.push({ item: 'Google login', ok: googleLogin })
    return checks
  })
  console.log('\n📊 Landing UI/UX:')
  landingChecks.forEach(c => console.log(`${c.ok ? '✅' : '❌'} ${c.item}: ${c.note || ''}`))
  // 2. Studio (auth guard var, landing'e atar)
  await page.setViewportSize({ width: 1920, height: 1080 })
  await page.goto('https://soundgit.online/studio', { waitUntil: 'networkidle' })
  await page.waitForTimeout(2000)
  const studioUrl = page.url()
  await page.screenshot({ path: 'studio-redirect.png', fullPage: true })
  console.log(`\n✅ Studio URL: ${studioUrl}`)
  console.log(`   Auth guard: ${studioUrl === 'https://soundgit.online/' || studioUrl === 'https://soundgit.online' ? '✅ Aktif - landing\'e attı!' : '❌ Aktif değil - studio\'ya girdi'}`)
  if (studioUrl.includes('/studio')) {
    await page.screenshot({ path: 'studio-desktop.png', fullPage: true })
    console.log('✅ Studio desktop screenshot: studio-desktop.png')
    const studioChecks = await page.evaluate(() => {
      const checks = []
      const v19 = document.body.innerHTML.includes('v19 Knolli')
      checks.push({ item: 'v19 Knolli başlık', ok: v19 })
      const laya = document.body.innerHTML.includes('Knolli Laya')
      checks.push({ item: 'Knolli Laya kartı', ok: laya })
      const meta = document.body.innerHTML.includes('Knolli Meta')
      checks.push({ item: 'Knolli Meta kartı', ok: meta })
      const friends = document.body.innerHTML.includes('Friends')
      checks.push({ item: 'Friends sistemi', ok: friends })
      const privacy = document.body.innerHTML.includes('Privacy')
      checks.push({ item: 'Privacy seçici', ok: privacy })
      return checks
    })
    console.log('\n📊 Studio v19 UI/UX:')
    studioChecks.forEach(c => console.log(`${c.ok ? '✅' : '❌'} ${c.item}`))
  }
  console.log('\n🎯 Görsel Beyin Önerileri:')
  console.log('- Landing: Sine wave var mı? Yoksa ekle, PondOS simgesi!')
  console.log('- Landing: 2 buton aynı stil mi? Open Studio + GitHub beyaz olmalı!')
  console.log('- Studio: 4 kart (Laya, Meta, Friends, Privacy) grid uyumlu mu?')
  console.log('- Studio: Upload alanı belirgin mi?')
  console.log('- Mobile: Responsive? 375px de test ettik!')
  await browser.close()
  console.log('\n✅ Screenshots: landing-desktop.png, landing-mobile.png, studio-redirect.png')
})()
